"""Regenerate Table 4 (robustness) straight from the attack study logs.

Every row is parsed out of experiments/logs_partial/<study>.log, so the table cannot drift from the
measurements. Studies that have not run yet are simply absent -- nothing is invented for them, and
the script says which it could not find.
"""
from __future__ import annotations

import re
from pathlib import Path

L = Path("D:/AUDIO_DEEPFAKE/experiments/logs_partial")
OUT = Path("D:/AUDIO_DEEPFAKE/paper/tables")
OUT.mkdir(parents=True, exist_ok=True)

# study -> (defence shown in the table, the run it attacks)
STUDIES = [
    ("adv_single", "single model"),
    ("adv_bands", "four layer bands"),
    ("adv_wavlm_from_xlsr", "WavLM, surrogate XLS-R"),
    ("adv_xlsr_from_wavlm", "XLS-R, surrogate WavLM"),
    ("adv_advtrain", "feature-space adv.\\ training"),
    ("adv_wavtrain", "\\textbf{waveform adv.\\ training}"),
    ("adv_control", "its control (Pool)"),
]
NAME = {"pgd_whitebox": "white-box PGD", "pgd_transfer": "transfer PGD", "spsa_blackbox": "SPSA"}
LINE = re.compile(r"(\w+)_snr(\d+)\s*\|\s*EER\s+([\d.]+)(?:\s*\(clean\s+([\d.]+)\))?"
                  r"\s*\|\s*success@FAR0\.1%\s+([\d.]+)")

rows: dict[tuple[str, str], dict] = {}
missing = []
for study, defence in STUDIES:
    path = L / f"{study}.log"
    if not path.exists():
        missing.append(study)
        continue
    text = path.read_text(encoding="utf-8", errors="ignore")
    # The clean EER belongs to the DEFENCE, not to one attack row: the SPSA line omits it, so take
    # the first value the study reports and carry it across that study's rows.
    seen = [m.group(4) for m in LINE.finditer(text) if m.group(4)]
    study_clean = seen[0] if seen else None
    for m in LINE.finditer(text):
        kind, snr, _eer, _clean, succ = m.groups()
        key = (defence, NAME.get(kind, kind))
        rows.setdefault(key, {"clean": study_clean})
        rows[key][snr] = float(succ)

lines = [
    "% generated by paper/robustness_table.py, do not edit by hand",
    "\\begin{tabular}{llrrr}", "\\toprule",
    "Defence & Attack & Clean \\eer{} & 30\\,dB & 20\\,dB \\\\", "\\midrule",
]
for (defence, attack), v in rows.items():
    clean = f"{float(v['clean']) * 100:.2f}" if v.get("clean") else "n/a"
    c30 = f"{v['30']:.3f}" if "30" in v else "n/a"
    c20 = f"{v['20']:.3f}" if "20" in v else "n/a"
    lines.append(f"{defence} & {attack} & {clean} & {c30} & {c20} \\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
(OUT / "robustness.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

print("\n".join(lines))
if missing:
    print("\n% NOT YET RUN, so absent from the table rather than guessed:", ", ".join(missing))
print("\nwrote", OUT / "robustness.tex")
